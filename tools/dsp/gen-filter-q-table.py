#!/usr/bin/env python3
"""Generates Source/modules/FilterQTable.h for DiceVox's filter (Phase 2A).

The filter is a resonant 12 dB/oct high-pass (low cut) followed by a resonant
12 dB/oct low-pass (high cut) sharing one Resonance control. When the two
cutoffs are close, their resonant peaks multiply: at equal cutoffs, Q x Q
(+15.9 dB at Q 2.5). This table gives the fraction of the dialled Q each stage may
use so that the COMBINED peak never exceeds the peak of a single stage at the
dialled resonance (about +8.1 dB at 100 %). Far-apart cutoffs get the full Q.

Index: resonance 0..100 % and the spacing between the cutoffs in octaves,
measured on the filters' prewarped (digital) frequencies, so the bound holds
exactly for the TPT filters at any sample rate. Each table entry is the minimum
safe fraction over its neighbouring cells, so interpolating between entries stays safe.

Needs numpy. Run from the repo root:
    python3 tools/dsp/gen-filter-q-table.py > Source/modules/FilterQTable.h
"""
import numpy as np

MIN_Q, MAX_Q = 0.70710678, 2.5     # must match FilterModule.h
OCT_MIN, OCT_MAX, OCT_STEP = -1.0, 5.0, 0.125
RES_STEP = 0.05                    # 0..1 in 5 % steps
FINE = 4                           # fine samples per table step (safety search)

octs = np.arange(OCT_MIN, OCT_MAX + 1e-9, OCT_STEP)
ress = np.arange(0.0, 1.0 + 1e-9, RES_STEP)

def res_to_q(r):
    return MIN_Q * (MAX_Q / MIN_Q) ** r

# Normalised frequency (low cut = 1), wide enough for both peaks at every spacing.
x2 = np.logspace(-1.5, np.log10(2.0 ** (OCT_MAX + OCT_STEP)) + 1.5, 2500) ** 2

def cascade_peak(d, q):
    """Peak |HP(x, q) * LP(x / 2^d, q)| (real-valued squared magnitudes); arrays over spacing."""
    q2 = (np.asarray(q, dtype=float) ** 2).reshape(-1, 1)
    r2 = (4.0 ** np.asarray(d, dtype=float)).reshape(-1, 1)
    xs = x2[None, :]
    hp2 = xs * xs / ((1 - xs) ** 2 + xs / q2)
    xl = xs / r2
    lp2 = 1 / ((1 - xl) ** 2 + xl / q2)
    return np.sqrt((hp2 * lp2).max(axis=1))

def single_peak(q):
    return np.sqrt((1 / ((1 - x2) ** 2 + x2 / q ** 2)).max())

def safe_q(d, r):
    """Largest stage Q (<= dialled Q) keeping the cascade at or under one stage's peak."""
    qt = res_to_q(r)
    target = single_peak(qt)
    d = np.atleast_1d(d)
    lo = np.full(d.shape, MIN_Q * 0.5)
    hi = np.full(d.shape, qt)
    ok_full = cascade_peak(d, hi) <= target
    for _ in range(30):
        mid = 0.5 * (lo + hi)
        ok = cascade_peak(d, mid) <= target
        lo = np.where(ok, mid, lo)
        hi = np.where(ok, hi, mid)
    return np.where(ok_full, qt, lo)

fine_octs = np.arange(OCT_MIN - OCT_STEP, OCT_MAX + OCT_STEP + 1e-9, OCT_STEP / FINE)
fine_ress = np.clip(np.arange(-RES_STEP, 1.0 + RES_STEP + 1e-9, RES_STEP / FINE), 0.0, 1.0)
fine = np.array([safe_q(fine_octs, r) / res_to_q(r) for r in fine_ress])  # [res, oct], fraction of dialled Q

table = np.zeros((len(ress), len(octs)))
for i, r in enumerate(ress):
    ri = np.abs(fine_ress - r) <= RES_STEP + 1e-9
    for j, d in enumerate(octs):
        dj = np.abs(fine_octs - d) <= OCT_STEP + 1e-9
        table[i, j] = fine[np.ix_(ri, dj)].min()

# 0 % resonance = two plain Butterworth stages, which can never add gain: keep them exact.
table[0, :] = 1.0

# Self-check: interpolate like FilterModule does, on a grid offset from the table
# (and past both ends), and report the worst combined peak vs one stage.
def stage_q(d, r):
    fo = np.clip((d - OCT_MIN) / OCT_STEP, 0, len(octs) - 1)
    fr = np.clip(r / RES_STEP, 0, len(ress) - 1)
    o0, r0 = np.minimum(fo.astype(int), len(octs) - 2), min(int(fr), len(ress) - 2)
    to, tr = fo - o0, fr - r0
    a = table[r0, o0] + to * (table[r0, o0 + 1] - table[r0, o0])
    b = table[r0 + 1, o0] + to * (table[r0 + 1, o0 + 1] - table[r0 + 1, o0])
    return res_to_q(r) * (a + tr * (b - a))

import sys
check_octs = np.arange(-3.0, 7.0, 0.0371)
worst, lost = -99.0, 0.0
for r in np.arange(0.0, 1.0001, 0.0137):
    q = stage_q(check_octs, r)
    excess = 20 * np.log10(cascade_peak(check_octs, q) / single_peak(res_to_q(r)))
    worst = max(worst, excess.max())
    far = check_octs > 4.0
    lost = max(lost, 1 - (q[far] / res_to_q(r)).min())
print(f"self-check: worst combined peak vs one stage {worst:+.3f} dB; "
      f"Q given up beyond 4 octaves at most {100 * lost:.2f} %", file=sys.stderr)
if worst > 0.05:
    sys.exit("table is not safe")

print("// Generated by tools/dsp/gen-filter-q-table.py. Do not edit by hand.")
print("#pragma once\n")
print("namespace FilterQTable\n{")
print(f"    constexpr float minOctaves = {OCT_MIN:.4f}f, octaveStep = {OCT_STEP:.4f}f, resonanceStep = {RES_STEP:.4f}f;")
print(f"    constexpr int numOctaves = {len(octs)}, numResonances = {len(ress)};\n")
print("    // Fraction of the dialled Q per stage: qFraction[resonance step][cutoff spacing step]")
print("    constexpr float qFraction[numResonances][numOctaves] = {")
for row in table:
    vals = ", ".join(f"{v:.4f}f" for v in row)
    print(f"        {{ {vals} }},")
print("    };")
print("}")
